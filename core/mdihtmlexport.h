/*FILE DESCRIPTION
/////////////////////////////////////////////////////////////////////////////
// Application: Katalog
// File Name:   mdihtmlexport.h
// Purpose:     Readable, distributable report of files (fork only, owner's
//              decision of 2026-10-30: HTML page only)
// Description: One self-contained HTML file per document, folder or catalog:
//              each file's information (the owner's), its people, the
//              proposals with their sources, the AI description and
//              classification, and for documents the full study with its
//              fragments. Accessible: lang attribute, semantic headings and
//              landmarks, a table of contents, alt texts, tables with
//              headers, readable without JavaScript (there is none), a print
//              style sheet; previews embedded as data URIs within a budget.
//              The words of the page come from the caller (translated in
//              the UI layer); English defaults are only a fallback.
/////////////////////////////////////////////////////////////////////////////
*/
#ifndef MDIHTMLEXPORT_H
#define MDIHTMLEXPORT_H

#include <QString>
#include <QStringList>
#include <QVariantMap>
#include <QVariantList>
#include <QHash>

class MdiHtmlExport
{
public:
    // Words of the page by key; see englishLabels() for the keys
    using Labels = QHash<QString, QString>;
    static Labels englishLabels();

    struct Options {
        QString title;               // page title (h1)
        QString subtitle;            // e.g. catalog and folder
        QString scope = QStringLiteral("file");   // "file", "folder", "catalog"
        QString language = QStringLiteral("en");  // html lang
        QString generatedText;       // "Generated by Teca on 30/10/2026"
        bool    embedPreviews = true;
        qint64  previewBudget = 24 * 1024 * 1024;   // bytes of embedded images
        qint64  maxPreviewBytes = 400 * 1024;       // one image
        bool    includeFragmentText = true;
    };

    // One file's record, gathered from mdi_data.db: `facts` (name, fullPath,
    // folder (relative), type, size (text), modified (text)) is completed with
    // information, people, proposals, ai {caption, tags, title, description,
    // categories, entities, summary, excerpts}, study (the "document" datum
    // value with its fragments) and preview (absolute path of the thumbnail)
    static QVariantMap fileRecord(const QString &mdiConnection, int catalogId, const QString &fullPath,
                                  const QVariantMap &facts);

    // The page. Records are grouped by their "folder", in the order given.
    static QString build(const QVariantList &records, const Options &options, const Labels &labels);

    // Writes atomically (QSaveFile); false with the reason
    static bool write(const QString &targetFile, const QString &html, QString *error);
};

#endif // MDIHTMLEXPORT_H
